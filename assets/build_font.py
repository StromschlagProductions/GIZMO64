def header_art():
    """320x24 real C64 pixels; x=240..287 is reserved for two wave sprites."""
    pixels = [[0] * 320 for _ in range(24)]

    def dot(x, y):
        if 0 <= x < 320 and 0 <= y < 24:
            pixels[y][x] = 1

    def horizontal(a, b, y):
        for x in range(a, b + 1):
            dot(x, y)

    # Twin rails stop exactly at the bevel and the dedicated sprite gap.
    for y in (8, 12):
        for a, b in ((8, 47), (193, 238), (289, 312)):
            horizontal(a, b, y)

    # Two-pixel bevelled enclosure, with no character-cell dependency.
    for y in (1, 2, 21, 22):
        horizontal(57, 183, y)
    for y in range(8, 16):
        for x in (50, 51, 189, 190):
            dot(x, y)
    for step in range(6):
        for width in (0, 1):
            dot(56 - step, 2 + step + width)
            dot(184 + step, 2 + step + width)
            dot(56 - step, 21 - step - width)
            dot(184 + step, 21 - step - width)

    # A bespoke broad, angular wordmark; the dialogue glyphs are untouched.
    letters = {
        'G': ('01111', '11000', '10000', '10111', '10001', '11001', '01111'),
        'I': ('11111', '00100', '00100', '00100', '00100', '00100', '11111'),
        'Z': ('11111', '00011', '00110', '01100', '11000', '10000', '11111'),
        'M': ('10001', '11011', '11111', '10101', '10001', '10001', '10001'),
        'O': ('01110', '11011', '10001', '10001', '10001', '11011', '01110'),
    }
    for index, letter in enumerate('GIZMO'):
        for gy, row in enumerate(letters[letter]):
            for gx, bit in enumerate(row):
                if bit == '1':
                    for dx in range(3):
                        for dy in range(2):
                            dot(70 + index * 21 + gx * 3 + dx, 5 + gy * 2 + dy)

    tiles = []
    codes = []
    for cy in range(3):
        for cx in range(40):
            tile = bytes(sum(pixels[cy * 8 + y][cx * 8 + x] << (7 - x)
                             for x in range(8)) for y in range(8))
            if not any(tile):
                codes.append(32)
            else:
                if tile not in tiles:
                    tiles.append(tile)
                codes.append(128 + tiles.index(tile))
    if len(tiles) > 128:
        raise ValueError(f'Header requires {len(tiles)} graphic characters')
    return tiles, codes


def build():
    font = bytearray(2048)
    for character, rows in GLYPHS.items():
        codes = [ord(character)]
        if "A" <= character <= "Z":
            codes.append(ord(character) - 64)
        for code in codes:
            for y, row in enumerate(rows):
                font[code * 8 + y] = int(row, 2) << 2
    font[95 * 8 + 3] = 0xff  # Durchgehende Trennlinie
    for y in range(7):
        font[96 * 8 + y] = 0x40  # Schmaler Cursor
    # Die obere Haelfte enthaelt gezielte inverse Zeichen.
    for code in range(128):
        for y in range(8):
            font[(code + 128) * 8 + y] = font[code * 8 + y] ^ 0xff
    tiles, _ = header_art()
    for index, tile in enumerate(tiles):
        font[(128 + index) * 8:(129 + index) * 8] = tile
    return bytes(font)


